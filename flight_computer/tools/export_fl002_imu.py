#!/usr/bin/env python3
"""Export fl002 IMU rows (liftoff - 5 s .. apogee) as a C header on stdout.

Usage: python3 -I export_fl002_imu.py <generate_charts.py> <fl002.cfl>
The sibling fl002.summary.json supplies liftoff and apogee; st002.txt the calibration.
Rows are raw int16: {ts_ms, ax, ay, az, gx, gy, gz}.
Conversions (applied by the consumer): acc 9.81/1024 m/s2 per LSB, gyro 0.07 dps per LSB.
"""
import importlib.util
import json
import os
import re
import sys


def main():
    charts_path, cfl_path = sys.argv[1], sys.argv[2]
    spec = importlib.util.spec_from_file_location("generate_charts", charts_path)
    gc = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gc)
    with open(os.path.join(os.path.dirname(cfl_path), "fl002.summary.json")) as f:
        summary = json.load(f)
    liftoff = summary["liftoff_ts_ms"]
    start = liftoff - 5000
    end = liftoff + round(summary["apogee_t_s"] * 1000)

    with open(os.path.join(os.path.dirname(cfl_path), "st002.txt")) as f:
        st = f.read()
    cal_angle = float(re.search(r"Angle:\s*(-?[\d.]+)", st).group(1))
    cal_axis = int(re.search(r"Axis:\s*(\d+)", st).group(1))

    imu = gc.parse_cfl(cfl_path)["records"]["IMU"]
    rows = sorted(r for r in imu if start <= r[0] <= end)
    liftoff_idx = next(i for i, r in enumerate(rows) if r[0] >= liftoff)

    print("// Generated by tools/export_fl002_imu.py from fl002.cfl; do not edit.")
    print("#pragma once")
    print("#include <cstddef>")
    print("#include <cstdint>")
    print()
    print("struct Fl002ImuRow {")
    print("  uint32_t ts_ms;")
    print("  int16_t ax, ay, az, gx, gy, gz;")
    print("};")
    print()
    print(f"constexpr size_t kFl002Rows = {len(rows)};")
    print(f"constexpr size_t kFl002LiftoffIndex = {liftoff_idx};")
    print("// st002 calibration: long axis and angle (firmware long_sign = sign(angle)).")
    print(f"constexpr int kFl002CalAxis = {cal_axis};")
    print(f"constexpr float kFl002CalAngleDeg = {cal_angle}F;")
    print("constexpr Fl002ImuRow kFl002Imu[kFl002Rows] = {")
    for r in rows:
        print("    {%d, %s}," % (r[0], ", ".join(str(v) for v in r[2:8])))
    print("};")


main()
